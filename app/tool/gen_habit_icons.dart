// A53: writes lib/widgets/habit_icon_catalog.g.dart from the hugeicons package (every free
// stroke-rounded glyph, by its kebab key) and contract-fixtures/habit/icons.json (category
// defaults, keyword table, featured icons). Run from app/: dart run tool/gen_habit_icons.dart
// test/widgets/habit_icons_test.dart checks the output against both sources.
import 'dart:convert';
import 'dart:io';

/// strokeRoundedBookOpen02 -> book-open-02 (the same rule as the fixture's keys).
String kebab(String name) => name
    .replaceAllMapped(RegExp(r'(?<=[a-z0-9])(?=[A-Z])'), (_) => '-')
    .replaceAllMapped(RegExp(r'(?<=[A-Z])(?=[A-Z][a-z])'), (_) => '-')
    .replaceAllMapped(RegExp(r'(?<=[A-Za-z])(?=[0-9])'), (_) => '-')
    .toLowerCase();

/// The hugeicons package's root, from the resolved package config.
Directory hugeiconsRoot() {
  final config = jsonDecode(File('.dart_tool/package_config.json').readAsStringSync()) as Map;
  final entry = (config['packages'] as List).cast<Map<String, dynamic>>().firstWhere(
    (p) => p['name'] == 'hugeicons',
  );
  final uri = Uri.parse(entry['rootUri'] as String);
  return Directory.fromUri(
    uri.isAbsolute ? uri : Directory.current.uri.resolve('.dart_tool/').resolveUri(uri),
  );
}

String dartString(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

void main() {
  final root = hugeiconsRoot();
  final pubspec = File('${root.path}/pubspec.yaml').readAsStringSync();
  final version = RegExp(r'^version:\s*(\S+)', multiLine: true).firstMatch(pubspec)!.group(1);
  final source = File('${root.path}/lib/styles/stroke_rounded.dart').readAsStringSync();
  final names = RegExp(
    r'^  static const List<List<dynamic>> strokeRounded([A-Za-z0-9]+) =',
    multiLine: true,
  ).allMatches(source).map((m) => m.group(1)!).toList();
  final keys = <String, String>{};
  final pattern = RegExp(r'^[a-z0-9]+(-[a-z0-9]+)*$');
  for (final name in names) {
    final key = kebab(name);
    if (!pattern.hasMatch(key) || key.length > 64 || keys.containsKey(key)) {
      throw StateError('Unusable or duplicate key $key from $name');
    }
    keys[key] = name;
  }

  final fixture =
      jsonDecode(File('../contract-fixtures/habit/icons.json').readAsStringSync()) as Map;
  final defaults = (fixture['category_defaults'] as Map).cast<String, String>();
  final keywords = (fixture['keywords'] as List).cast<Map<String, dynamic>>();
  final featured = (fixture['featured'] as List).cast<Map<String, dynamic>>();
  for (final key in [
    ...defaults.values,
    ...keywords.map((k) => k['icon'] as String),
    ...featured.map((f) => f['key'] as String),
  ]) {
    if (!keys.containsKey(key)) {
      throw StateError('icons.json names $key, not in hugeicons $version');
    }
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_habit_icons.dart from hugeicons $version and')
    ..writeln('// contract-fixtures/habit/icons.json. Do not edit; run the tool again.')
    ..writeln()
    ..writeln("import 'package:hugeicons/hugeicons.dart';")
    ..writeln()
    ..writeln('/// The hugeicons version the keys come from.')
    ..writeln("const habitIconSetVersion = '$version';")
    ..writeln()
    ..writeln('/// Every free stroke-rounded glyph, by its kebab key (A53).')
    ..writeln('const Map<String, List<List<dynamic>>> habitIconGlyphs = {');
  keys.forEach((key, name) => out.writeln('  ${dartString(key)}: HugeIcons.strokeRounded$name,'));
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// The icon a category shows while a habit has none (or one this app does not know).',
    )
    ..writeln('const Map<String, String> habitIconCategoryDefaults = {');
  defaults.forEach((c, key) => out.writeln('  ${dartString(c)}: ${dartString(key)},'));
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// The keyword table: word prefixes of a habit name, to an icon. Tried in order.')
    ..writeln('const List<(List<String>, String)> habitIconKeywords = [');
  for (final k in keywords) {
    final prefixes = (k['prefixes'] as List).cast<String>().map(dartString).join(', ');
    out.writeln('  ([$prefixes], ${dartString(k['icon'] as String)}),');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// The icons the picker shows first, with their English labels.')
    ..writeln('const List<(String, String)> habitIconFeatured = [');
  for (final f in featured) {
    out.writeln('  (${dartString(f['key'] as String)}, ${dartString(f['label'] as String)}),');
  }
  out.writeln('];');
  File('lib/widgets/habit_icon_catalog.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${keys.length} icons (hugeicons $version).');
}
